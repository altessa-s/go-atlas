package grpc

//go:generate go run github.com/altessa-s/go-atlas/cmd/optgen generate --type=options

import (
	"net"
	"time"

	"github.com/altessa-s/go-atlas/transport/internal/timeouts"

	"google.golang.org/grpc"

	baseserver "github.com/altessa-s/go-atlas/transport/internal/server"
)

// DefaultTimeoutConfig returns the default timeout configuration.
// These values provide reasonable defaults for most production deployments
// while allowing customization for specific requirements.
func DefaultTimeoutConfig() timeouts.Config {
	return timeouts.Default()
}

// DefaultStartupVerification is how long [Server.Start] waits for the serving
// goroutine to fail before reporting a successful start.
const DefaultStartupVerification = timeouts.DefaultStartupVerification

// options holds the merged configuration for [Server], combining base server
// settings (address, TLS, logger, timeouts) with gRPC-specific settings
// (server options, reflection). The gRPC-specific fields are code-generated
// by optgen; baseOpts is composed manually via [WithBaseOptions].
type options struct {
	// baseOpts holds base server options (no opt tag - managed manually)
	baseOpts []baseserver.Option

	// gRPC-specific options (generated by optgen)
	grpcOpts   []grpc.ServerOption `opt:"GrpcOptions"`
	reflection bool                `opt:"Reflection" optgen:"default=false"`

	// listener, when set, is served instead of a TCP listener on the
	// configured address — e.g. a bufconn listener in tests. The server
	// closes it on shutdown.
	listener net.Listener `optgen:"notnil"`

	// startupVerification is how long Start waits for the serving goroutine
	// to report an early error before declaring the start successful. Zero
	// or negative skips the wait (an early serve error is then only logged).
	// A base timeouts option passed through WithBaseOptions takes precedence.
	startupVerification time.Duration `optgen:"default=DefaultStartupVerification" optval:"nonpositive"`
}

// WithBaseOptions adds base server options (TLS, listener, logger, address, name, timeouts).
// This is a convenience function to avoid duplicating wrapper functions for each base server option.
//
// Example:
//
//	srv, _ := grpc.New(
//	    grpc.WithBaseOptions(
//	        server.WithAddress(":50051"),
//	        server.WithLogger(slog.Default()),
//	        server.WithTLSConfig(tlsConfig),
//	    ),
//	    grpc.WithReflection(true),
//	)
func WithBaseOptions(opts ...baseserver.Option) Option {
	return func(c *options) {
		c.baseOpts = append(c.baseOpts, opts...)
	}
}
