package mongo

import (
	"go.mongodb.org/mongo-driver/v2/bson"

	"github.com/altessa-s/go-atlas/domain/behavior"
)

//go:generate go run github.com/altessa-s/go-atlas/cmd/optgen generate

// DefaultBSONTagName is the default struct tag key read to resolve a field's
// document name and modifiers (omitempty, omitonupdate). Override with
// [WithBsonTagName].
const DefaultBSONTagName = "bson"

// options carries translator configuration. Tunables are generated by optgen —
// never construct this struct directly; use the With* options.
//
// The translators own only the bson tag; field-behavior concerns (tag name,
// depth, strip kinds) belong to the behavior engine and are configured there via
// [github.com/altessa-s/go-atlas/domain/behavior.WithTagName] /
// [github.com/altessa-s/go-atlas/domain/behavior.WithMaxDepth] /
// [github.com/altessa-s/go-atlas/domain/behavior.WithKinds].
type options struct {
	bsonTagName string `optgen:"default=DefaultBSONTagName"`
	// registry is the BSON registry the driver encodes with. A type it
	// encodes with an encoder of its own (a type encoder, such as the
	// data/mongo/bsoncodec decimal codec) is written as a unit rather than
	// folded field by field, and the insert document is encoded with it.
	// Nil means the driver's default registry.
	registry *bson.Registry
	// policy is the engine's field-behavior policy, bound by behavior.New
	// through [docTranslator.BindPolicy] — never an option: the zero Policy
	// (default tag key, nothing stripped) until then. The update translator
	// judges the values it cannot resolve by it (see [options.protectedType]).
	policy behavior.Policy `opt:"-"`
}
